// Read-only checks of the [test] PRs in brianv0/rico against live GitHub. Needs a running Rico (npm start,
// with GITHUB_TOKEN) and `npm install`. Posts nothing.  Usage: node e2e/real/check-prs.cjs
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
let failed = false;
const step = async (n, fn) => { try { await fn(); console.log('ok   ' + n); } catch (e) { failed = true; console.log('FAIL ' + n + '\n     ' + String(e.message).split('\n')[0].slice(0, 300)); } };
const SWEEP = () => {
  const doc = document.getElementById('doc'), R = window.__rico, lines = R.state.lines;
  const norm = (s) => s.toLowerCase().replace(/[^\p{L}\p{N}\s]/gu, ' ');
  const words = (s) => norm(s).split(/\s+/).filter(Boolean);
  const leaves = [...doc.querySelectorAll('[data-l]')].filter((e) => !e.querySelector('[data-l]'));
  const tn = (el) => { const w = document.createTreeWalker(el, NodeFilter.SHOW_TEXT); const a = []; for (let n = w.nextNode(); n; n = w.nextNode()) if (n.data.trim()) a.push(n); return a; };
  const sel = (a, b) => { const A = tn(a), B = tn(b); if (!A.length || !B.length) return null; const r = document.createRange(); r.setStart(A[0], 0); const l = B[B.length - 1]; r.setEnd(l, l.data.length); return r; };
  const eff = (ln, dir) => { let k = ln; while (k >= 1 && k <= lines.length && !words(lines[k - 1]).length) k += dir; return k; };
  const bad = []; let n = 0;
  const step = leaves.length > 400 ? Math.ceil(leaves.length / 400) : 1;
  for (let i = 0; i < leaves.length; i += step) for (const j of [i, Math.min(leaves.length - 1, i + 5)]) {
    const r = sel(leaves[i], leaves[j]); if (!r) continue; n++;
    const d = R.describeSelection(r); if (!d) { bad.push({ i, j, why: 'null' }); continue; }
    const w = words(r.toString());
    if (w[0] && !words(lines[eff(d.start, 1) - 1] || '').includes(w[0])) bad.push({ i, j, d: [d.start, d.end], first: w[0], line: lines[d.start - 1] });
    if (w.length && !words(lines[eff(d.end, -1) - 1] || '').includes(w[w.length - 1])) bad.push({ i, j, d: [d.start, d.end], last: w[w.length - 1], line: lines[d.end - 1] });
  }
  return { n, bad: bad.slice(0, 5), nbad: bad.length };
};
(async () => {
  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: 1500, height: 950 } });
  const errors = [];
  page.on('pageerror', (e) => errors.push(e.message));
  page.on('console', (m) => m.type() === 'error' && errors.push(m.text()));
  const load = async (n, file) => {
    await page.goto(`http://localhost:${process.env.PORT || 4317}/#pr=${encodeURIComponent('brianv0/rico#' + n)}${file ? '&f=' + encodeURIComponent(file) : ''}`);
    await page.evaluate(() => localStorage.clear());
    await page.reload();
    await page.waitForFunction(() => window.__rico && window.__rico.state.file && document.querySelector('#doc [data-l]'), null, { timeout: 60000 });
    await page.waitForTimeout(400);
  };
  const noOverlap = () => page.evaluate(() => { const r = [...document.querySelectorAll('#margin .thread')].map((e) => e.getBoundingClientRect()).sort((a, b) => a.top - b.top); return r.every((x, i) => i === 0 || x.top >= r[i - 1].bottom - 0.5); });

  // ---------------- PR 1: multi-hunk edit with real threads ----------------
  await load(1);
  await step('PR1: 5 threads in the margin + a note for the removed-line thread', async () => {
    assert.ok((await page.locator('#margin .thread').count()) >= 5, 'at least the five seeded threads (real reviews add more)');
    assert.match(await page.locator('#margin .note').innerText(), /1 thread on removed lines/);
  });
  await step('PR1: real author names, markdown bodies and the Claude footer render', async () => {
    const t = await page.locator('#margin').innerText();
    assert.match(t, /brianv0/); assert.match(t, /cannot/); assert.match(t, /Generated by Claude Code/);
    assert.equal(await page.locator('#margin .thread strong').first().innerText(), 'cannot');
  });
  await step('PR1: the /api/health thread (outdated) is labelled and still placed', async () => {
    const card = page.locator('#margin .thread', { hasText: 'api/health' });
    assert.equal(await card.count(), 1);
    assert.match(await card.innerText(), /Outdated/); assert.match(await card.innerText(), /Not shipped/);
  });
  await step('PR1: the 3-message thread shows all messages, in order', async () => {
    const card = page.locator('#margin .thread', { hasText: 'reads like an apology' });
    assert.equal(await card.locator('.msg').count(), 3);
    assert.match(await card.innerText(), /apology[\s\S]*Agreed on promoting[\s\S]*Third message/);
  });
  await step('PR1: cards sit beside their text and never overlap', async () => {
    assert.equal(await noOverlap(), true);
    const [cardTop, blockTop] = await page.evaluate(() => { const c = [...document.querySelectorAll('#margin .thread')].find((e) => e.innerText.includes('concrete example')); const b = [...document.querySelectorAll('#doc li')].find((e) => e.innerText.includes('Degrade gracefully')); return [c.getBoundingClientRect().top, b.getBoundingClientRect().top]; });
    assert.ok(Math.abs(cardTop - blockTop) < 40, `card ${cardTop} vs block ${blockTop}`);
  });
  await step('PR1: diff markers match the real patch (changed vs context vs outside)', async () => {
    const c = await page.evaluate(() => ({ chg: document.querySelectorAll('#doc .chg').length, ctx: document.querySelectorAll('#doc .ctx').length, out: document.querySelectorAll('#doc .out').length }));
    assert.ok(c.chg >= 5 && c.ctx > 0 && c.out > 5, JSON.stringify(c));
  });
  await step('PR1: line mapping exact across the whole real architecture.md', async () => {
    const r = await page.evaluate(SWEEP);
    assert.ok(r.n > 100); assert.equal(r.nbad, 0, JSON.stringify(r.bad));
  });
  await step('PR1: relative image (SVG) loads via /api/raw', async () => {
    assert.ok(await page.evaluate(() => { const i = document.querySelector('#doc img'); return i.complete && i.naturalWidth > 0; }));
  });

  // ---------------- PR 2: added file + modified file, real PNG ----------------
  await load(2, 'docs/guide/faq.md');
  await step('PR2: added file, 2 threads, no per-block "changed" noise', async () => {
    assert.equal(await page.locator('#margin .thread').count(), 2);
    assert.equal(await page.locator('#doc .chg').count(), 0);
    assert.equal(await page.evaluate(() => window.__rico.state.file.status), 'added');
  });
  await step('PR2: real PNG loads from the head commit (320x120)', async () => {
    await page.waitForFunction(() => { const i = document.querySelector('#doc img'); return i && i.complete && i.naturalWidth > 0; }, null, { timeout: 15000 });
    assert.deepEqual(await page.evaluate(() => { const i = document.querySelector('#doc img'); return [i.naturalWidth, i.naturalHeight]; }), [320, 120]);
  });
  await step('PR2: line mapping exact (tables, fences, lists)', async () => {
    const r = await page.evaluate(SWEEP); assert.equal(r.nbad, 0, JSON.stringify(r.bad));
  });
  await page.locator('#files button[data-path$="getting-started.md"]').click();
  await page.waitForFunction(() => window.__rico.state.file.filename.endsWith('getting-started.md'));
  await step('PR2: second file (modified) opens with its own diff', async () => {
    assert.ok(await page.locator('#doc .chg').count() > 0);
  });

  // ---------------- PR 3: rename / pure rename / delete ----------------
  await load(3);
  await step('PR3: lists renamed + pure-renamed files, not the deleted one', async () => {
    const joined = (await page.locator('#files button').evaluateAll((bs) => bs.map((b) => b.dataset.path))).join('|');
    assert.match(joined, /reference\/glossary\.md/); assert.match(joined, /guide\/quickstart\.md/); assert.doesNotMatch(joined, /old-notes/);
  });
  await page.locator('#files button[data-path$="quickstart.md"]').click();
  await page.waitForFunction(() => window.__rico.state.file.filename.endsWith('quickstart.md'));
  await step('PR3: pure rename (no patch) renders, every block is "outside the diff"', async () => {
    const c = await page.evaluate(() => ({ chg: document.querySelectorAll('#doc .chg').length, ctx: document.querySelectorAll('#doc .ctx').length, out: document.querySelectorAll('#doc .out').length }));
    assert.equal(c.chg + c.ctx, 0); assert.ok(c.out > 3);
  });
  await step('PR3: commenting there is routed to the summary, not an invalid inline anchor', async () => {
    const d = await page.evaluate(() => { const li = document.querySelector('#doc p'); const w = document.createTreeWalker(li, NodeFilter.SHOW_TEXT); const n = w.nextNode(); const r = document.createRange(); r.setStart(n, 0); r.setEnd(n, Math.min(10, n.length)); const x = window.__rico.describeSelection(r); return { anchor: x.anchor }; });
    assert.equal(d.anchor, null);
  });
  await page.locator('#files button[data-path$="glossary.md"]').click();
  await page.waitForFunction(() => window.__rico.state.file.filename.endsWith('glossary.md'));
  await step('PR3: renamed+edited file shows its real thread', async () => {
    await page.waitForTimeout(300);
    assert.equal(await page.locator('#margin .thread').count(), 1);
    assert.match(await page.locator('#margin .thread').innerText(), /alphabetical/);
  });

  // ---------------- PR 4: 2000+ lines ----------------
  const t0 = Date.now();
  await load(4);
  const loadMs = Date.now() - t0;
  const meta = await page.evaluate(() => ({ lines: window.__rico.state.lines.length, blocks: document.querySelectorAll('#doc [data-l]').length }));
  console.log(`     PR4 ${meta.lines} lines, ${meta.blocks} blocks, page ready in ${loadMs} ms`);
  await step('PR4: loads and renders in a reasonable time', async () => assert.ok(loadMs < 8000, loadMs + 'ms'));
  await step('PR4: line mapping exact over a sampled sweep of the long doc', async () => {
    const t = Date.now(); const r = await page.evaluate(SWEEP); console.log(`     ${r.n} selections in ${Date.now() - t} ms`);
    assert.equal(r.nbad, 0, JSON.stringify(r.bad));
  });
  await step('PR4: selecting deep in the document is instant', async () => {
    const ms = await page.evaluate(() => { const ps = [...document.querySelectorAll('#doc p')]; const p = ps[Math.floor(ps.length * 0.9)]; p.scrollIntoView(); const w = document.createTreeWalker(p, NodeFilter.SHOW_TEXT); const n = w.nextNode(); const r = document.createRange(); r.setStart(n, 0); r.setEnd(n, 20); const t = performance.now(); window.__rico.describeSelection(r); return performance.now() - t; });
    assert.ok(ms < 50, ms + 'ms');
  });
  await step('no page errors across all PRs', async () => assert.deepEqual(errors, [], JSON.stringify(errors)));
  await browser.close();
  process.exit(failed ? 1 : 0);
})();
