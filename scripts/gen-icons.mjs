// Generates public/icons.js from @primer/octicons (the icons GitHub itself uses).
// Run: node scripts/gen-icons.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = path.join(root, 'node_modules/@primer/octicons/build/svg');
const NAMES = [
  'mark-github', 'chevron-down', 'chevron-right', 'copy', 'file', 'file-directory-fill', 'file-directory-open-fill', 'diff', 'code', 'eye',
  'check', 'comment', 'comment-discussion', 'git-pull-request', 'git-pull-request-draft', 'git-merge', 'git-pull-request-closed',
  'triangle-down', 'plus', 'x', 'sidebar-expand', 'sidebar-collapse', 'filter', 'kebab-horizontal', 'link', 'info', 'light-bulb', 'report',
  'alert', 'stop', 'diff-added', 'diff-modified', 'diff-removed', 'diff-renamed', 'unfold', 'file-code', 'check-circle-fill', 'dot-fill', 'git-commit',
  'gear', 'arrow-right', 'sign-out',
];
const out = {};
for (const n of NAMES) {
  const f = path.join(dir, `${n}-16.svg`);
  if (!fs.existsSync(f)) { console.error('missing icon', n); continue; }
  const svg = fs.readFileSync(f, 'utf8').trim();
  const inner = svg.replace(/^<svg[^>]*>/, '').replace(/<\/svg>$/, '');
  out[n] = inner;
}
const body = `// GENERATED by scripts/gen-icons.mjs from @primer/octicons (MIT). Do not edit.\nconst PATHS = ${JSON.stringify(out, null, 1)};\n\n`
  + `/** An inline 16px Octicon as an SVG string. */\nexport const icon = (name, { size = 16, cls = '' } = {}) =>\n  \`<svg class="octicon \${cls}" viewBox="0 0 16 16" width="\${size}" height="\${size}" fill="currentColor" aria-hidden="true">\${PATHS[name] || ''}</svg>\`;\n`;
fs.writeFileSync(path.join(root, 'public/icons.js'), body);
console.log('wrote public/icons.js with', Object.keys(out).length, 'icons');
