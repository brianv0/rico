// node genlinebreak.mjs <uniseg source dir (rivo/uniseg v0.4.7)>: writes public/d2/linebreak.js, a port of uniseg's
// FirstLineSegmentInString (Unicode line breaking, UAX #14, as lib/textmeasure's native Markdown painter uses it) restricted to
// U+0000..U+00FF: the state transition table comes from linerules.go, the properties from lineproperties.go. Other characters
// throw: the callers defer such Markdown.
import fs from 'node:fs';
import path from 'node:path';

const dir = process.argv[2];
const rules = fs.readFileSync(path.join(dir, 'linerules.go'), 'utf8');
const props = fs.readFileSync(path.join(dir, 'lineproperties.go'), 'utf8');
const properties = fs.readFileSync(path.join(dir, 'properties.go'), 'utf8');

// constant blocks of properties.go: iota numbering
const constBlocks = [...properties.matchAll(/const \(\n([\s\S]*?)\n\)/g)].map((m) => m[1]);
const nums = {};
for (const block of constBlocks) {
  let iota = 0;
  for (const line of block.split('\n')) {
    const m = /^\s*(\w+)\s*(?:=\s*([^/\s]+))?/.exec(line);
    if (!m || line.trim().startsWith('//')) continue;
    const name = m[1];
    if (m[2] !== undefined && m[2] !== 'iota' && /^\d/.test(m[2])) nums[name] = Number(m[2]);
    else nums[name] = iota;
    iota++;
  }
}
// linerules.go state constants
const lbBlock = /const \(\n(\tlbAny = iota[\s\S]*?)\n\)/.exec(rules)[1];
const lb = {};
{
  let iota = 0;
  for (const line of lbBlock.split('\n')) {
    const m = /^\s*(\w+)\s*(?:=\s*([^/\s]+))?/.exec(line);
    if (!m) continue;
    lb[m[1]] = m[2] !== undefined && /^\d/.test(m[2]) ? Number(m[2]) : iota;
    iota++;
  }
}
const val = (name) => (name in lb ? lb[name] : name.startsWith('pr') || name.startsWith('gc') ? nums[name] : (() => { throw new Error(name); })());

const table = {};
for (const m of rules.matchAll(/case (\w+) \| (\w+)<<32:\n\s*return (\w+), (\w+), (\d+)/g)) {
  const [, st, pr, ns, brk, rule] = m;
  table[`${val(st)},${val(pr)}`] = [val(ns), { LineDontBreak: 0, LineCanBreak: 1, LineMustBreak: 2 }[brk], Number(rule)];
}
// the code points up to U+00FF: [start, end, prop]
const cps = [];
for (const m of props.matchAll(/\{0x([0-9A-F]+), 0x([0-9A-F]+), (\w+), (\w+)\}/g)) {
  const s = parseInt(m[1], 16), e = parseInt(m[2], 16);
  if (s > 0xff) break;
  cps.push([s, Math.min(e, 0xff), nums[m[3]], nums[m[4]]]);
}
const prop = new Array(256).fill(null);
for (const [s, e, p, g] of cps) for (let r = s; r <= e; r++) prop[r] = [p, g];

const lbNames = Object.fromEntries(Object.entries(lb));
const out = `// This Source Code Form is subject to the terms of the Mozilla Public License, v. 2.0.
// If a copy of the MPL was not distributed with this file, You can obtain one at https://mozilla.org/MPL/2.0/.
//
// Generated by tools/d2ref/genlinebreak.mjs from github.com/rivo/uniseg v0.4.7 (MIT, Copyright (c) 2019 Oliver Kuederle): the
// line break parser (line.go, linerules.go, UAX #14 as of Unicode 15) for U+0000..U+00FF. Do not edit the tables.

const LB = ${JSON.stringify(lbNames)};
const PR = ${JSON.stringify(Object.fromEntries(Object.entries(nums).filter(([k]) => k.startsWith('pr'))))};
const GC = ${JSON.stringify(Object.fromEntries(Object.entries(nums).filter(([k]) => k.startsWith('gc'))))};
const lbBlock = ${JSON.stringify(table)};
// [line break property, general category] of U+0000..U+00FF
const PROPS = ${JSON.stringify(prop)};

const LineDontBreak = 0, LineCanBreak = 1, LineMustBreak = 2;
const { lbZWJBit, lbCPeaFWHBit } = LB;
const lbTransitions = (state, prop) => lbBlock[state + ',' + prop] ?? [-1, -1, -1];

export class UnsupportedRune extends Error {}

function propertyLineBreak(r) {
  if (r > 0xff) throw new UnsupportedRune('line break property of U+' + r.toString(16));
  return PROPS[r];
}

// transitionLineBreakState: [newState, lineBreak]; rest is the string after r (for the LB25 look ahead)
function transitionLineBreakState(state, r, rest) {
  let [nextProperty, generalCategory] = propertyLineBreak(r);
  let forceNoBreak = false, isCPeaFWH = false;
  if (state >= 0 && (state & lbCPeaFWHBit) !== 0) {
    isCPeaFWH = true; // LB30: CP but ea is not F, W, or H.
    state &= ~lbCPeaFWHBit;
  }
  if (state >= 0 && (state & lbZWJBit) !== 0) {
    state &= ~lbZWJBit;
    forceNoBreak = true; // LB8a.
  }
  const finish = (newState, lineBreak) => {
    // Transition into LB30 (every character up to U+00FF has an East Asian width other than F, W, H)
    if (newState === LB.lbCP || newState === LB.lbNUCP) newState |= lbCPeaFWHBit;
    if (forceNoBreak) lineBreak = LineDontBreak;
    return [newState, lineBreak];
  };

  // LB1.
  if (nextProperty === PR.prAI || nextProperty === PR.prSG || nextProperty === PR.prXX) nextProperty = PR.prAL;
  else if (nextProperty === PR.prSA) nextProperty = generalCategory === GC.gcMn || generalCategory === GC.gcMc ? PR.prCM : PR.prAL;
  else if (nextProperty === PR.prCJ) nextProperty = PR.prNS;

  // Combining marks.
  if (nextProperty === PR.prZWJ || nextProperty === PR.prCM) {
    const bit = nextProperty === PR.prZWJ ? lbZWJBit : 0;
    const mustBreakState = state < 0 || state === LB.lbBK || state === LB.lbCR || state === LB.lbLF || state === LB.lbNL;
    if (!mustBreakState && state !== LB.lbSP && state !== LB.lbZW && state !== LB.lbQUSP && state !== LB.lbCLCPSP && state !== LB.lbB2SP) {
      return finish(state | bit, LineDontBreak); // LB9.
    }
    // LB10.
    return finish(LB.lbAL | bit, mustBreakState ? LineMustBreak : LineCanBreak);
  }

  // Find the applicable transition in the table.
  let [newState, lineBreak, rule] = lbTransitions(state, nextProperty);
  if (newState < 0) {
    // No specific transition found. Try the less specific ones.
    const [anyPropProp, anyPropLineBreak, anyPropRule] = lbTransitions(state, PR.prAny);
    const [anyStateProp, anyStateLineBreak, anyStateRule] = lbTransitions(LB.lbAny, nextProperty);
    if (anyPropProp >= 0 && anyStateProp >= 0) {
      // Both apply. We'll use a mix.
      newState = anyStateProp; lineBreak = anyStateLineBreak; rule = anyStateRule;
      if (anyPropRule < anyStateRule) { lineBreak = anyPropLineBreak; rule = anyPropRule; }
    } else if (anyPropProp >= 0) {
      [newState, lineBreak, rule] = [anyPropProp, anyPropLineBreak, anyPropRule];
    } else if (anyStateProp >= 0) {
      [newState, lineBreak, rule] = [anyStateProp, anyStateLineBreak, anyStateRule];
    } else {
      // No known transition. LB31: ALL ÷ ALL.
      [newState, lineBreak, rule] = [LB.lbAny, LineCanBreak, 310];
    }
  }

  // LB12a.
  if (rule > 121 && nextProperty === PR.prGL &&
    (state !== LB.lbSP && state !== LB.lbBA && state !== LB.lbHY && state !== LB.lbLB21a && state !== LB.lbQUSP && state !== LB.lbCLCPSP && state !== LB.lbB2SP)) {
    return finish(LB.lbGL, LineDontBreak);
  }

  // LB13.
  if (rule > 130 && state !== LB.lbNU && state !== LB.lbNUNU) {
    switch (nextProperty) {
      case PR.prCL: return finish(LB.lbCL, LineDontBreak);
      case PR.prCP: return finish(LB.lbCP, LineDontBreak);
      case PR.prIS: return finish(LB.lbIS, LineDontBreak);
      case PR.prSY: return finish(LB.lbSY, LineDontBreak);
    }
  }

  // LB25 (look ahead). Go's && binds tighter than ||: a following HY always triggers the look ahead.
  if ((rule > 250 && (state === LB.lbPR || state === LB.lbPO) && nextProperty === PR.prOP) || nextProperty === PR.prHY) {
    if (rest.length > 0) {
      const cp = rest.codePointAt(0);
      const pr = propertyLineBreak(cp)[0];
      if (pr === PR.prNU) return finish(LB.lbNU, LineDontBreak);
    }
  }

  // LB30 (part one).
  if (rule > 300) {
    if ((state === LB.lbAL || state === LB.lbHL || state === LB.lbNU || state === LB.lbNUNU) && nextProperty === PR.prOP) {
      return finish(LB.lbOP, LineDontBreak);
    } else if (isCPeaFWH) {
      switch (nextProperty) {
        case PR.prAL: return finish(LB.lbAL, LineDontBreak);
        case PR.prHL: return finish(LB.lbHL, LineDontBreak);
        case PR.prNU: return finish(LB.lbNU, LineDontBreak);
      }
    }
  }

  // LB30a.
  if (newState === LB.lbAny && nextProperty === PR.prRI) {
    if (state !== LB.lbOddRI && state !== LB.lbEvenRI) return finish(LB.lbOddRI, lineBreak);
    if (state === LB.lbOddRI) return finish(LB.lbEvenRI, LineDontBreak);
    return finish(LB.lbOddRI, lineBreak);
  }

  // LB30b (no character up to U+00FF is an unassigned Extended_Pictographic).
  if (rule > 302 && nextProperty === PR.prEM) {
    if (state === LB.lbEB || state === LB.lbExtPicCn) return finish(PR.prAny, LineDontBreak);
  }

  return finish(newState, lineBreak);
}

/** uniseg.FirstLineSegmentInString: [segment, rest, mustBreak, newState]. Strings are JS strings of characters up to U+00FF. */
export function firstLineSegmentInString(str, state) {
  if (str.length === 0) return ['', '', false, 0];
  let length = 1;
  // every supported character is one UTF-16 unit
  if (str.length <= length) return [str, '', true, LB.lbAny]; // LB3.
  if (state < 0) [state] = transitionLineBreakState(state, str.codePointAt(0), str.slice(length));
  for (;;) {
    const r = str.codePointAt(length);
    const l = r > 0xffff ? 2 : 1;
    let boundary;
    [state, boundary] = transitionLineBreakState(state, r, str.slice(length + l));
    if (boundary !== LineDontBreak) return [str.slice(0, length), str.slice(length), boundary === LineMustBreak, state];
    length += l;
    if (str.length <= length) return [str, '', true, LB.lbAny]; // LB3.
  }
}
`;
fs.writeFileSync(new URL('../../public/d2/linebreak.js', import.meta.url), out);
